# **다시 해도 같은 것.** 우리가 직접 쓴 사유 문장에서 따왔습니다
# (collector/transcript.py · llm/runner.py). 여기 없는 것은 모르는
# 실패이고, 모르는 실패는 한 번 더 해 볼 만하다고 봅니다.
PERMANENT_MARKS = (
    # **모델이 "요약할 수 없다"고 판단한 것.** 고장이 아니라 판정입니다.
    #
    # 실측(2026-08-20): 요약 실패 47건 중 **43건**이 이것이었습니다. 판정은
    # 전부 irrelevant(41)·promotional(2) 이고, 근거는 "한국어 영상을
    # 일본어로 오인식한 ASR 결과물", "21초짜리 뉴스 쇼츠" 같은 것들이었죠 —
    # 다시 부르면 같은 자막을 읽고 같은 결론을 냅니다. 실제로 한 편이
    # 38번을 그렇게 돌았습니다.
    #
    # 자막이 깨진 쪽은 **자막부터 다시 받아야** 풀립니다. 요약을 다시
    # 부르는 일과는 다른 길이라, 여기서 "다시 해 볼 만한 것"에 섞으면
    # 누를 때마다 40편이 딸려 가서 토큰만 씁니다.
    "요약이 오지 않았습니다",
    # 자막을 받긴 받았는데 요약할 것이 없습니다 — 다시 받아도 같습니다.
    "요약할 내용이 없",
    # 받아쓰기 상한을 넘는 길이. 상한을 올리기 전에는 같습니다.
    "너무 깁니다",
    # 영상 쪽이 사라졌거나 잠긴 것.
    "비공개",
    "삭제된",
    "멤버십",
    "지역 제한",
    "private",
    "deleted",
    "unavailable",
)


def retryable(reason: str | None) -> bool:
    """다시 줄에 세워 볼 만한가. **모르면 그렇다고 봅니다.**"""
    low = (reason or "").lower()
    return not any(m.lower() in low for m in PERMANENT_MARKS)
