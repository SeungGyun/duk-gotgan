"""잡이 살아 있다는 신호 — **돌아왔는가가 아니라 진척이 있었는가.**

워치독은 `run_once` 가 돌아오는지로 살았는지를 판단했습니다
(scripts/worker.py). 잡 하나가 한 틱에 한 가지 일만 하던 때는 맞는
셈법이었지만, 지금 요약 한 호출은 대기를 스무 편까지 붙잡고 돌고 한 편에
2~5분이 걸립니다. 그래서 **네 편을 멀쩡히 담는 동안** 이렇게 찍혔습니다.

    01:29:40 워커 시작 — review 60초
    01:32:13 [agy] pg9ga4ix5_M 담았습니다. 전문성 26점
    01:33:50 [agy] DwrwsRj8Z7s 담았습니다. 전문성 92점
    01:38:54 [agy] 67Uj3muPLpc 담았습니다. 전문성 72점
    01:39:40 [watchdog] review 잡이 10분째 한 바퀴도 못 돌았습니다 — 어딘가에 붙들려 있습니다

**일하는 중에 울리는 경보는 다음부터 안 읽힙니다.** 정말 붙들린 것과 그냥
오래 걸리는 것은 다른 일이고, 둘을 가르는 값은 "마지막으로 한 걸음
나아간 때"입니다.

프로세스 안에만 둡니다. 읽는 쪽(워치독)이 같은 프로세스에 있고, 재시작하면
잊어도 되는 값입니다 — 갓 뜬 워커는 애초에 붙들려 있지 않습니다.
"""

import time

# 잡 이름 → (마지막 걸음 시각, 그때 무엇을 하고 있었나)
_beats: dict[str, tuple[float, str]] = {}


def beat(job: str, what: str = "") -> None:
    """한 걸음 나아갔습니다.

    `what` 은 **지금 손에 쥔 것**입니다 — 방금 끝낸 것이 아니라. 붙들렸을
    때 경보에 실려야 쓸모가 있는 값은 "무엇을 하다 멈췄나" 쪽입니다.
    """
    _beats[job] = (time.monotonic(), what)


def last(job: str) -> tuple[float, str] | None:
    """(마지막 걸음 시각, 그때 하던 일). 한 번도 안 찍었으면 None."""
    return _beats.get(job)


def forget(job: str) -> None:
    _beats.pop(job, None)
